// ─── Date Resolution & Lead-Time Helpers ──────────────────────────────────────

export interface ResolvedStockEvent extends StockCalendarEvent {
  nextDate: Date;
  nextIsoDate: string;
  daysUntil: number;
  idealUploadDaysUntil: number;
  inUploadWindowNow: boolean;
}

function parseIsoLocal(iso: string): Date {
  const [y, m, d] = iso.split("-").map(Number);
  return new Date(y, m - 1, d);
}

function toIsoDate(d: Date): string {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${y}-${m}-${day}`;
}

export function resolveEventTiming(
  event: StockCalendarEvent,
  referenceDate: Date = new Date()
): ResolvedStockEvent {
  const ref = new Date(
    referenceDate.getFullYear(),
    referenceDate.getMonth(),
    referenceDate.getDate()
  );
  const currentYear = ref.getFullYear();

  const candidateForYear = (yr: number): Date => {
    if (yr === 2026 && event.movableDates?.[2026]) {
      return parseIsoLocal(event.movableDates[2026]);
    }
    if (yr === 2027 && event.movableDates?.[2027]) {
      return parseIsoLocal(event.movableDates[2027]);
    }
    return new Date(yr, event.month - 1, event.day);
  };

  let nextDate = candidateForYear(currentYear);
  if (nextDate.getTime() < ref.getTime()) {
    nextDate = candidateForYear(currentYear + 1);
  }

  const msPerDay = 86_400_000;
  const daysUntil = Math.round((nextDate.getTime() - ref.getTime()) / msPerDay);
  const leadDays = event.leadWeeks * 7;
  const idealUploadDaysUntil = daysUntil - leadDays;

  // Prime upload window: from (leadWeeks + 4 weeks) before event down to 21 days before event
  const inUploadWindowNow =
    daysUntil >= 21 && daysUntil <= leadDays + 28;

  return {
    ...event,
    nextDate,
    nextIsoDate: toIsoDate(nextDate),
    daysUntil,
    idealUploadDaysUntil,
    inUploadWindowNow,
  };
}

export function resolveAllEvents(
  referenceDate: Date = new Date()
): ResolvedStockEvent[] {
  return STOCK_CALENDAR_EVENTS.map((ev) => resolveEventTiming(ev, referenceDate)).sort(
    (a, b) => a.daysUntil - b.daysUntil
  );
}

/**
 * Matches events on or near an exact month/day (default window ±14 days around the chosen date)
 * so picking any date on the calendar surfaces both exact-day matches and nearby seasonal opportunities.
 */
export function findEventsNearDate(
  events: ResolvedStockEvent[],
  targetMonth: number,
  targetDay: number,
  windowDays = 14
): Array<ResolvedStockEvent & { dayDistance: number }> {
  const refYear = 2026; // non-leap neutral 365-day circle
  const target = new Date(refYear, targetMonth - 1, targetDay).getTime();
  const msPerDay = 86_400_000;

  return events
    .map((ev) => {
      const evMonth = ev.nextDate.getMonth() + 1;
      const evDay = ev.nextDate.getDate();
      const d1 = Math.abs(
        Math.round((new Date(refYear, evMonth - 1, evDay).getTime() - target) / msPerDay)
      );
      const circularDist = Math.min(d1, 365 - d1);
      return { ...ev, dayDistance: circularDist };
    })
    .filter((ev) => ev.dayDistance <= windowDays)
    .sort((a, b) => {
      if (a.dayDistance !== b.dayDistance) return a.dayDistance - b.dayDistance;
      const rank = { Peak: 0, High: 1, Steady: 2 };
      return rank[a.demandLevel] - rank[b.demandLevel];
    });
}
